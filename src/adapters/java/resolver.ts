import type { GraphNode, SpecifierResolver } from "../../core/capabilities/contracts.ts";

/**
 * Class names to files of the tree (ADR-0008 §1): `a.b.C` is the file `…/a/b/C.java` (or .groovy,
 * .kt) under any source root; of several (modules of one build), the one nearest the importing file.
 * A nested class `a.b.C.Inner` is its outer class's file. A class outside the tree is its package
 * (`pkg:org.example.web`); a candidate (`?a.b.C`, a type named in the code) outside the tree is no
 * edge at all.
 *
 * With the tree's nodes it resolves members too: `spec:type:Name` (a supertype as written) to the
 * class's node, `spec:call:Type#method/arity` to the method's node — looked up in the class and its
 * supertypes, by arity, else by name — or the class's node when the method is not declared in the
 * tree (inherited from a library, generated by Lombok). Names resolve as javac would: a type of the
 * same file, a single-type import, the same package, an on-demand import. A call into a library is
 * no edge; a library supertype is its class (`pkg:org.example.Repository`).
 */
export const JAVA_RESOLVER_VERSION = 2;

interface TypeEntry {
  readonly id: string;
  readonly file: string;
  readonly supers: readonly string[];
  /** `name/arity` → method node id. */
  readonly methods: Map<string, string>;
}

interface FileScope {
  readonly pkg: string;
  readonly imports: readonly string[];
  readonly wildcards: readonly string[];
  /** Simple and nested names of the types the file declares → fqn. */
  readonly declared: Map<string, string>;
}

const strs = (v: unknown): string[] =>
  Array.isArray(v) ? v.filter((x): x is string => typeof x === "string") : [];

const SOURCE = /\.(java|groovy|kt)$/;

function sharedPrefix(a: string, b: string): number {
  let i = 0;
  while (i < a.length && i < b.length && a[i] === b[i]) i += 1;
  return i;
}

export class JavaResolver implements SpecifierResolver {
  /** `a/b/C` (a path without the source root and extension) → files ending with it, by its last segment. */
  private readonly byName = new Map<string, string[]>();
  private readonly types = new Map<string, TypeEntry>();
  private readonly scopes = new Map<string, FileScope>();

  constructor(files: ReadonlySet<string>, nodes: readonly GraphNode[] = []) {
    for (const f of files) {
      if (!SOURCE.test(f)) continue;
      const name = f.replace(/^.*\//, "").replace(SOURCE, "");
      this.byName.set(name, [...(this.byName.get(name) ?? []), f]);
    }
    this.index(nodes);
  }

  private index(nodes: readonly GraphNode[]): void {
    const methods: GraphNode[] = [];
    for (const n of nodes) {
      const m = n.metadata ?? {};
      if ((n.kind === "Module" || n.kind === "Test") && n.file && Array.isArray(m.imports))
        this.scopes.set(n.file, {
          pkg: typeof m.package === "string" ? m.package : "",
          imports: strs(m.imports),
          wildcards: strs(m.wildcards),
          declared: new Map(),
        });
      else if (n.kind === "Type" && typeof m.fqn === "string" && n.file)
        this.types.set(m.fqn, {
          id: n.id,
          file: n.file,
          supers: [...strs(m.extends), ...strs(m.implements)],
          methods: new Map(),
        });
      else if (n.kind === "Function") methods.push(n);
    }
    for (const [fqn, t] of this.types) {
      const scope = this.scopes.get(t.file);
      if (!scope) continue;
      const path = t.id.slice(t.id.indexOf("#") + 1);
      // `Outer.Inner` is known in its file as itself, as `Inner`, and its outer as `Outer`
      scope.declared.set(path, fqn);
      scope.declared.set(path.replace(/^.*\./, ""), fqn);
    }
    const byId = new Map([...this.types.values()].map((t) => [t.id, t]));
    for (const m of methods) {
      const cut = m.id.lastIndexOf(".");
      const owner = byId.get(m.id.slice(0, cut));
      owner?.methods.set(m.id.slice(cut + 1), m.id);
    }
  }

  /** A type name as written in `file` → its fqn in the tree, `ext:<fqn>` outside it, undefined unknown. */
  private typeIn(file: string, raw: string): string | undefined {
    const scope = this.scopes.get(file);
    if (!scope || !raw) return undefined;
    if (raw.includes(".")) {
      if (this.types.has(raw)) return raw;
      const [first, ...rest] = raw.split(".");
      const outer = this.typeIn(file, first as string);
      if (outer && !outer.startsWith("ext:")) {
        const nested = `${outer}.${rest.join(".")}`;
        if (this.types.has(nested)) return nested;
      }
      return /^[a-z]/.test(raw) ? `ext:${raw}` : undefined;
    }
    const declared = scope.declared.get(raw);
    if (declared) return declared;
    const imported = scope.imports.find((i) => i === raw || i.endsWith(`.${raw}`));
    if (imported) return this.types.has(imported) ? imported : `ext:${imported}`;
    const same = scope.pkg ? `${scope.pkg}.${raw}` : raw;
    if (this.types.has(same)) return same;
    for (const w of scope.wildcards) if (this.types.has(`${w}.${raw}`)) return `${w}.${raw}`;
    return undefined;
  }

  /** The method `name/arity` of a class or its supertypes (arity -1: by name), nearest first. */
  private member(fqn: string, name: string, arity: number): string | undefined {
    const seen = new Set<string>();
    const queue = [fqn];
    let byName: string | undefined;
    while (queue.length > 0) {
      const at = queue.shift() as string;
      if (seen.has(at)) continue;
      seen.add(at);
      const t = this.types.get(at);
      if (!t) continue;
      if (arity >= 0) {
        const exact = t.methods.get(`${name}/${arity}`);
        if (exact) return exact;
      }
      if (!byName) for (const [key, id] of t.methods) if (key.startsWith(`${name}/`)) byName = id;
      for (const s of t.supers) {
        const r = this.typeIn(t.file, s);
        if (r && !r.startsWith("ext:")) queue.push(r);
      }
    }
    return byName;
  }

  resolve(from: string, spec: string): string | null | undefined {
    if (spec.startsWith("type:") || spec.startsWith("call:")) {
      const file = from.slice(0, from.indexOf("#") < 0 ? undefined : from.indexOf("#"));
      if (spec.startsWith("type:")) {
        const t = this.typeIn(file, spec.slice(5));
        if (!t) return null;
        return t.startsWith("ext:") ? `pkg:${t.slice(4)}` : (this.types.get(t)?.id ?? null);
      }
      const m = /^call:(.+)#([^#/]+)\/(-?\d+)$/.exec(spec);
      const t = m ? this.typeIn(file, m[1] as string) : undefined;
      if (!m || !t || t.startsWith("ext:")) return null;
      const target = this.member(t, m[2] as string, Number(m[3])) ?? this.types.get(t)?.id;
      return target && target !== from ? target : null;
    }
    const candidate = spec.startsWith("?");
    const name = candidate ? spec.slice(1) : spec;
    if (!/^[\w.]+$/.test(name)) return undefined;
    const parts = name.split(".");
    // the longest prefix that is a class of the tree: a.b.C.Inner → a.b.C
    for (let n = parts.length; n >= 1; n -= 1) {
      const last = parts[n - 1] as string;
      if (!/^[A-Z]/.test(last)) break;
      const file = this.fileOf(from, parts.slice(0, n));
      if (file) return file === from ? null : file;
    }
    if (candidate) return null;
    const pkg = parts.filter(
      (p, i) => !/^[A-Z]/.test(p) && parts.slice(0, i).every((q) => !/^[A-Z]/.test(q)),
    );
    return `pkg:${(pkg.length > 0 ? pkg : parts).join(".")}`;
  }

  private fileOf(from: string, parts: readonly string[]): string | undefined {
    const tail = `${parts.join("/")}`;
    const found = (this.byName.get(parts.at(-1) as string) ?? []).filter((f) => {
      const stem = f.replace(SOURCE, "");
      return stem === tail || stem.endsWith(`/${tail}`);
    });
    if (found.length <= 1) return found[0];
    return [...found].sort((a, b) => sharedPrefix(b, from) - sharedPrefix(a, from) || a.localeCompare(b))[0];
  }
}
